/**
 * 입력한 연도 기준 띠 및 육십간지 계산
 */
export function getKoreanZodiac(birthYear: number): {
  zodiacName: string;
  ganjiName: string;
  description: string;
  colorName: string;
} {
  // 입력한 연도 기준 직접 계산
  const effectiveYear = birthYear;

  // 10간 계산: (연도 - 4) % 10
  const stemIndex = ((effectiveYear - 4) % 10 + 10) % 10;
  // 12지 계산: (연도 - 4) % 12
  const branchIndex = ((effectiveYear - 4) % 12 + 12) % 12;

  const stem = HEAVENLY_STEMS[stemIndex];
  const branch = ZODIAC_ANIMALS[branchIndex];

  const zodiacName = `${branch.name}띠`;
  const ganjiName = `${stem.name}${branch.name}년`;
  const description = `${stem.colorName} ${branch.name}의 해 (${stem.name}${branch.name}년)`;

  return {
    zodiacName,
    ganjiName,
    description,
    colorName: stem.colorName,
  };
}
